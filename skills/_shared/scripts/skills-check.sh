#!/bin/bash
# Проверка того, что скилы этого репозитория подхватываются агентом.
#
# Использование:  skills-check.sh [каталог обнаружения]
# По умолчанию:   <корень репозитория>/.claude/skills
#
# Что проверяется для каждой записи каталога обнаружения:
#   1. запись — символьная ссылка, а не подменивший её обычный файл;
#   2. SKILL.md по этой ссылке читается;
#   3. фронтматтер: name непуст, совпадает с именем каталога, kebab-case,
#      не длиннее 64 символов, не содержит слов claude и anthropic;
#      description непуст, не длиннее 1024 символов, без угловых скобок;
#   4. имена скилов не повторяются.
#
# Коды возврата:
#   0  все проверки прошли
#   1  проверка не прошла: в выводе названо, что именно
#   2  неверные аргументы
#   3  каталог обнаружения недоступен либо пуст
#
# Ограничения 64 и 1024 — из требований к фронтматтеру скилов: имя длиннее
# 64 символов и описание длиннее 1024 отвергаются при загрузке. Слова claude
# и anthropic в имени запрещены там же.

set -euo pipefail

NAME_MAX=64
DESC_MAX=1024

usage() {
  echo "Использование: $(basename "$0") [каталог обнаружения]" >&2
  echo "По умолчанию — .claude/skills в корне репозитория." >&2
}

[ $# -le 1 ] || { usage; exit 2; }

if [ $# -eq 1 ]; then
  DIR="$1"
else
  ROOT="$(git rev-parse --show-toplevel 2>/dev/null)" || {
    echo "Не репозиторий git: каталог по умолчанию определить не из чего." >&2
    echo "Указать каталог обнаружения аргументом." >&2
    exit 3; }
  DIR="$ROOT/.claude/skills"
fi

[ -d "$DIR" ] || { echo "Каталога обнаружения нет: $DIR" >&2; exit 3; }

ENTRIES="$(ls -1 "$DIR" 2>/dev/null || true)"
[ -n "$ENTRIES" ] || { echo "Каталог обнаружения пуст: $DIR" >&2; exit 3; }

FAILED=0   # был ли хоть один отказ за прогон, определяет код возврата
BAD=0      # был ли отказ у текущего скила, сбрасывается на каждой итерации
NAMES=""

fail() {
  echo "   ОТКАЗ: $1" >&2
  FAILED=1
  BAD=1
}

# Длина значения в символах, а не в байтах. ${#var} в bash зависит от локали:
# при LANG=C кириллическая буква считается за два байта, и описание на русском
# языке ложно превышает предел. Продолжающие байты UTF-8 лежат в диапазоне
# 0x80-0xBF; байты минус продолжающие дают число символов при любой локали.
chars() {
  b="$(printf '%s' "$1" | wc -c | tr -d ' ')"
  k="$(printf '%s' "$1" | tr -d -c '\200-\277' | wc -c | tr -d ' ')"
  echo $((b - k))
}

# Значение поля фронтматтера. Фронтматтер — блок между первой строкой ---
# и следующей строкой ---. Значение может занимать несколько строк:
# берётся всё до строки, начинающейся с другого поля, либо до конца блока.
field() {
  sed -n '2,/^---$/p' "$1" \
    | sed -n "/^$2:/,\$p" \
    | sed "1s/^$2:[[:space:]]*//" \
    | sed '2,$ { /^[a-z_][a-z_]*:/,$ d; }' \
    | sed 's/^---$//' \
    | tr '\n' ' ' \
    | sed 's/[[:space:]]*$//' \
    | sed 's/^"//; s/"$//'
}

for e in $ENTRIES; do
  p="$DIR/$e"
  BAD=0
  echo "-- $e"

  if [ ! -L "$p" ]; then
    if [ -f "$p" ]; then
      fail "не символьная ссылка, а обычный файл. Симлинки в клоне отключены."
      echo "   Разбор: git config --get core.symlinks; git ls-files -s $p" >&2
      echo "   Починка: git config core.symlinks true && git checkout -- $p" >&2
      continue
    fi
    # Обычный каталог со скилом внутри — не наша раскладка, но рабочая.
    echo "   не ссылка, а каталог: раскладка отличается от принятой"
  fi

  if [ ! -r "$p/SKILL.md" ]; then
    fail "SKILL.md не читается по пути $p/SKILL.md"
    continue
  fi

  if [ "$(head -1 "$p/SKILL.md")" != "---" ]; then
    fail "первая строка SKILL.md не ---, фронтматтера нет"
    continue
  fi

  n="$(field "$p/SKILL.md" name)"
  d="$(field "$p/SKILL.md" description)"

  nlen="$(chars "$n")"
  dlen="$(chars "$d")"

  [ -n "$n" ] || fail "поле name пусто"
  [ "$n" = "$e" ] || fail "name «$n» не совпадает с именем каталога «$e»"
  [ "$nlen" -le "$NAME_MAX" ] || fail "name длиннее $NAME_MAX символов: $nlen"
  printf '%s' "$n" | grep -Eq '^[a-z0-9]+(-[a-z0-9]+)*$' \
    || fail "name не kebab-case: «$n»"
  printf '%s' "$n" | grep -qiE 'claude|anthropic' \
    && fail "name содержит запрещённое слово claude или anthropic" || true

  [ -n "$d" ] || fail "поле description пусто"
  [ "$dlen" -le "$DESC_MAX" ] || fail "description длиннее $DESC_MAX символов: $dlen"
  case "$d" in
    *"<"*|*">"*) fail "description содержит угловые скобки" ;;
  esac

  NAMES="$NAMES $n"
  [ "$BAD" -eq 1 ] || echo "   ок: name=$n, description $dlen симв."
done

DUPES="$(printf '%s\n' $NAMES | sort | uniq -d)"
if [ -n "$DUPES" ]; then
  echo "Повторяющиеся имена скилов: $DUPES" >&2
  FAILED=1
fi

if [ "$FAILED" -eq 0 ]; then
  echo "Все скилы прошли проверку: $(printf '%s\n' $NAMES | wc -l | tr -d ' ') шт."
  exit 0
fi

echo "Проверка не прошла: отмеченные ОТКАЗ скилы не отвечают требованиям к фронтматтеру." >&2
exit 1
