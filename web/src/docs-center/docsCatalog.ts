export function getDocsArticleBySlug(slug?: string | null): DocsArticle | undefined {
  if (!slug) return undefined
  return DOCS_ARTICLES.find((article) => article.slug === slug)
}

export function getDocsSectionMeta(sectionId: DocsArticle['section']): DocsSectionMeta {
  return DOCS_SECTIONS.find((section) => section.id === sectionId) || DOCS_SECTIONS[0]
}
