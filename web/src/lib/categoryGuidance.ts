export const STANDARD_CATALOG_EXACT_CATEGORY_NAMES = Object.keys(CATEGORY_GUIDANCE_BY_EXACT_NAME)

export const STANDARD_CATALOG_GUIDANCE_COUNT = STANDARD_CATALOG_EXACT_CATEGORY_NAMES.length

/** Нормализация тире в имени категории для совпадения с ключами каталога */
function normalizeCategoryKey(name: string): string {
  return name.trim().replace(/\s*[\u2014\u2013\-]\s*/g, CATEGORY_NAME_SEP)
}

/**
 * Подсказка по точному имени категории, затем по префиксу специализации (до « — »), иначе generic.
 */
export function categoryGuidanceRootClassName(level: CategoryGuidanceLevel, variant: 'desktop' | 'mobile'): string {
  return variant === 'mobile'
    ? `mobileCategoryGuidance mobileCategoryGuidance--${level}`
    : `categoryGuidanceBlock categoryGuidanceBlock--${level}`
}

export function getCategoryGuidance(categoryName: string | null | undefined): CategoryGuidance {
  const raw = (categoryName || '').trim()
  if (!raw) return GENERIC_CATEGORY_GUIDANCE

  const exact = CATEGORY_GUIDANCE_BY_EXACT_NAME[raw]
  if (exact) return exact

  const normalized = normalizeCategoryKey(raw)
  const exactNorm = CATEGORY_GUIDANCE_BY_EXACT_NAME[normalized]
  if (exactNorm) return exactNorm

  const sepMatch = raw.split(/\s*[\u2014\u2013\-]\s*/)
  const prefix = sepMatch[0]?.trim() ?? ''
  if (prefix && CATEGORY_GUIDANCE_BY_SPECIALIZATION_PREFIX[prefix]) {
    return CATEGORY_GUIDANCE_BY_SPECIALIZATION_PREFIX[prefix]!
  }

  return GENERIC_CATEGORY_GUIDANCE
}
