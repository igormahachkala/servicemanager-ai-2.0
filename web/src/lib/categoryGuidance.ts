export type CategoryGuidanceLevel = 'normal' | 'caution' | 'urgent'

export type CategoryGuidance = {
  title: string
  level: CategoryGuidanceLevel
  steps: readonly string[]
}

/** Разделитель как в seed: пробел + длинное тире + пробел */
export const CATEGORY_NAME_SEP = ' \u2014 '

const G = (
  title: string,
  level: CategoryGuidanceLevel,
  steps: readonly string[],
): CategoryGuidance => ({ title, level, steps })

