--
-- Вкладка «История» выбирает заявки одной единицы в порядке
-- (createdAt desc, id desc) и берёт их страницами. Индекса по одному
-- equipmentId для этого мало: он отбирает строки, но порядок приходится
--строить сортировкой на каждой странице.
--
-- Миграция аддитивная: только индекс, ни одной колонки не меняется.
-- CONCURRENTLY не применяется намеренно — Prisma выполняет миграцию
-- в транзакции, а таблица заявок здесь порядка тысячи строк, и обычное
-- построение индекса занимает миллисекунды.
CREATE INDEX IF NOT EXISTS "Ticket_equipmentId_createdAt_idx" ON "Ticket"("equipmentId", "createdAt");
