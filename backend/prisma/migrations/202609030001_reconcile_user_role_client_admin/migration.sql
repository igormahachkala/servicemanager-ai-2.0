-- SMA-MIGRATION-HISTORY-RECONCILIATION-090
--
-- Единственный объект класса B, который действительно отсутствует в базе,
-- собранной по одной лишь истории миграций: значение UserRole.CLIENT_ADMIN.
--
-- Как возникло расхождение:
--   schema.prisma          — значение есть;
--   история миграций       — не создаёт его ни одной командой;
--   Stage и Production     — значение есть в обеих базах.
-- То есть оно попало в живые контуры мимо миграций. Пока историю не починить,
-- новая установка «с нуля» получит enum без CLIENT_ADMIN, а код на него уже
-- опирается (technicians.service.ts, resolveAdminProfile.ts и другие) — то есть
-- сломается именно чистая установка, а не работающие контуры.
--
-- Почему только этот пункт получает миграцию, а остальные три — нет:
--   индекс ServiceContract_clientCompanyId_role_status_idx, DEFAULT у
--   UserAccessScope.updatedAt и фактическое имя уникального индекса
--   ServiceContractSpecialization уже создаются существующими миграциями и
--   присутствуют в обеих базах. Расходилась там только schema.prisma, поэтому
--   они приведены в соответствие правкой схемы. Менять ради них работающую
--   базу — а Prisma предлагала DROP INDEX и DROP DEFAULT — значило бы
--   ломать живое ради красивого diff.
--
-- Свойства этой миграции:
--   * идемпотентна: на Stage и Production все проверки коротко замыкаются,
--     не выполняется ни одной DDL-команды, не затрагивается ни одна строка;
--   * на чистой базе добавляет ровно одно значение enum;
--   * необратимых операций нет: ни DROP, ни ALTER COLUMN, ни переименований.
--
-- Откат: PostgreSQL не поддерживает удаление значения enum. Обратный шаг —
-- пересоздание типа со всеми значениями, кроме CLIENT_ADMIN, что возможно
-- только при отсутствии строк с этим значением. Практически откат не требуется:
-- на обоих контурах значение уже существовало до этой миграции.

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
      FROM pg_enum e
      JOIN pg_type t ON t.oid = e.enumtypid
     WHERE t.typname = 'UserRole'
       AND e.enumlabel = 'CLIENT_ADMIN'
  ) THEN
    -- Значение добавляется В КОНЕЦ, без AFTER, и это осознанный выбор.
    --
    -- Порядок значений enum в PostgreSQL задаёт сортировку колонки этого типа,
    -- а код сортирует по роли в трёх местах: users.service.ts и дважды в
    -- permissions.service.ts (orderBy: [{ role: 'asc' }, { email: 'asc' }]).
    --
    -- В живых базах порядок сложился исторически и уже не совпадает с порядком
    -- объявления в schema.prisma (там PLATFORM_ADMIN первый, в базах — девятый).
    -- Воспроизвести объявленный порядок можно было бы только пересозданием типа,
    -- то есть разрушительной операцией на работающей базе.
    --
    -- Зато базовая часть типа на чистой установке и в живых контурах совпадает
    -- значение в значение. Дописывая CLIENT_ADMIN в конец, мы получаем на чистой
    -- установке ровно тот же порядок, что уже действует на Stage и Production, —
    -- и списки пользователей сортируются одинаково везде. Вариант с
    -- AFTER 'ADMIN' выглядел бы аккуратнее в схеме, но давал бы новым установкам
    -- другой порядок сортировки, чем у существующих.
    ALTER TYPE "UserRole" ADD VALUE 'CLIENT_ADMIN';
  END IF;
END
$$;
