/**
 * SMA-BACKEND-BOOT-GATE-076.
 *
 * Постоянный сторож графа зависимостей Nest.
 *
 * Отвергнутый RC 1c1992e6 проходил всё: 1544 теста бэкенда, сборку, проверки
 * Prisma, фронтенд и merge-checks, — и при этом приложение на Stage не
 * поднималось. `InspectionScheduleService` просил третьим аргументом
 * `TicketsAssignmentService`, `InspectionModule` импортировал `TicketsModule`,
 * а тот этот провайдер экспортировал: по коду всё сходилось. Не сходилось
 * в момент сборки графа — `TicketsModule` стоит в кольце
 * Tickets → Notifications → forwardRef(MaxBot) → forwardRef(Tickets),
 * и его экспорт не оказывался готов для импортёра без forwardRef.
 *
 * Почему этого не видел ни один из 1544 тестов: они собирают сервисы руками,
 * `new InspectionScheduleService(prisma, contracts, assignment)`, минуя
 * контейнер. Почему не видела сборка: это отказ разрешения во время работы,
 * а не ошибка типов — экспорт существует и типизирован верно.
 *
 * Поэтому проверка ровно одна и настоящая: собрать тот же граф, что собирает
 * `main.ts`, из того же `AppModule`.
 *
 * `.compile()`, а не `NestFactory.create`: он создаёт весь граф — каждый
 * модуль, каждый провайдер, каждый конструктор, — но останавливается до
 * `onModuleInit`. Это важно: в `onModuleInit` живут `$connect()` к базе,
 * опрос MAX и пять таймеров (SLA, автозакрытие смен, realtime, rate-limiter).
 * Ни один из них здесь не стартует, поэтому проверка не ходит в сеть,
 * не держит открытых хендлов и укладывается в пару секунд.
 *
 * Ничего не подменяется. Подмена `AppModule` или любого модуля кольца
 * (Tickets, Notifications, MaxBot, Inspection) убрала бы ровно то ребро,
 * ради которого тест написан. `PrismaService` тоже настоящий: конструктора
 * у него нет, соединение открывает `onModuleInit`, куда мы не доходим.
 * Правило на будущее: подменять здесь можно только листовую инфраструктуру
 * и только если её конструктор действительно ходит наружу.
 *
 * Чего этот сторож НЕ закрывает, и на что полагаться нельзя: всё, что идёт
 * после сборки графа. `useGlobalPipes`, `enableCors`, `realtime.attach`,
 * `app.listen`, любой отказ внутри `onModuleInit`, расхождение миграций.
 * Это остаётся за сверкой после развёртывания — шаг 10 sma-deploy-stage.
 */

/*
 * Переменные ставятся здесь, а не берутся из `.env` контура.
 *
 * `AppModule` требует `JWT_SECRET` в момент импорта: `auth.module.ts`
 * вызывает `getJwtSecret()` на верхнем уровне. Если бы значение приходило
 * из окружения разработчика, проверка падала бы или проходила в зависимости
 * от чужой машины, а merge-checks подкладывает `.env` контура только ради
 * `prisma:generate`.
 *
 * Значения заведомо нерабочие и никуда не ведут. DSN нужен конструктору
 * `PrismaClient`, но соединение по нему не открывается: до `onModuleInit`
 * дело не доходит.
 *
 * Присваивания стоят ВЫШЕ импортов намеренно. `import { AppModule }`
 * компилируется в `require` на своём месте и выполняет верхний уровень
 * `auth.module.ts` немедленно, поэтому переменные должны быть выставлены
 * до него. Перенос этого блока вниз — под импорты или в `beforeAll` —
 * ломает проверку отказом «Required environment variable JWT_SECRET».
 */
